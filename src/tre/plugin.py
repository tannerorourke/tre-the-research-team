"""Claude Code plugin skills generated from the persona charters, so each
charter has one source. 'test_plugin_sync.py' fails when the two drift.

    tre plugin-sync            # from the plugin root: rewrite skills/<slug>/SKILL.md
    tre plugin-sync --root DIR
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from .agents.personas import PERSONAS, Persona


@dataclass(frozen=True)
class PersonaSkill:
    persona: str
    slug: str
    description: str


PERSONA_SKILLS = (
    PersonaSkill(
        "rs", "research-scientist",
        "Take the TRE Research Scientist's charter: question framing, literature, falsifiable "
        "hypotheses, pre-registered designs, analysis, and interpretation against computed "
        "statistics. Use when the user asks what a study should find out, what results mean, "
        "or wants a design or write-up judged as the lab's scientist would.",
    ),
    PersonaSkill(
        "tl", "tech-lead",
        "Take the TRE Tech Lead's charter: architecture, decomposition into tickets a Developer "
        "can finish without guessing, rubric-ordered code review, and feasibility checks of "
        "experiment designs. Use when the user asks how a study gets built and run, wants a "
        "ticket written, or wants a change reviewed as the lab's tech lead would.",
    ),
)


def render_skill(skill: PersonaSkill, persona: Persona) -> str:
    # -- a JSON string is a valid YAML scalar; the descriptions carry ': '
    return (
        f"---\nname: {skill.slug}\ndescription: {json.dumps(skill.description)}\n---\n\n"
        f"<!-- Generated by 'tre plugin-sync' from tre.agents.personas ({persona.key!r}). "
        f"Edit the persona, then re-run the command. -->\n\n"
        f"{persona.system.strip()}\n"
    )


def skill_path(root: Path, skill: PersonaSkill) -> Path:
    return root / "skills" / skill.slug / "SKILL.md"


def sync(root: Path) -> list[Path]:
    written = []
    for skill in PERSONA_SKILLS:
        target = skill_path(root, skill)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_skill(skill, PERSONAS[skill.persona]))
        written.append(target)
    return written
